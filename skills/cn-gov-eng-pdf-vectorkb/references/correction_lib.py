def norm_num(tok: str) -> str:
    """纯数字串内的形近字母归一。仅当整个 token 由数字与误识字母(O/l/I/Z)及小数点/加减号组成，且含误识字母时替换。"""
    if re.fullmatch(r"[0-9OIlZ.,+\-]+", tok) and ('O' in tok or 'l' in tok or 'I' in tok or 'Z' in tok):
        return tok.replace('O', '0').replace('l', '1').replace('I', '1').replace('Z', '2')
    return tok


MOJIBAKE = set("ĆÆðÑĢďâèî¼öô»ºÓñý")


def is_garbage(t: str) -> bool:
    """判断一行是否为图像型页漏出的二进制乱码。"""
    if any(ord(c) < 0x20 for c in t):          # 控制字符
        return True
    if any(c in MOJIBAKE for c in t):          # 典型 mojibake
        return True
    if len(t) > 2 and not re.search(r"[\u4e00-\u9fffA-Za-z0-9]", t):
        return True
    return False


def fix(t: str) -> str:
    for a, b in CORR:
        t = t.replace(a, b)
    t = re.sub(r"第(\d+)草", r"第\1章", t)     # OCR 把「章」识成「草」
    t = re.sub(r"[0-9OIlZ.,+\-]+", lambda m: norm_num(m.group(0)), t)
    return t


def is_heading(line: str):
    """探测子章节标题，返回 (level, text) 或 None。level: '###' / '####'。"""
    s = line.strip()
    if not s:
        return None
    if re.match(r"^\d+\.\d+(\.\d+)?\s+[\u4e00-\u9fff]", s):
        return ("###", s)
    if re.match(r"^（[一二三四五六七八九十]+）", s):
        return ("####", s)
    if re.match(r"^[一二三四五六七八九十]+、", s) and len(s) < 40:
        return ("###", s)
    if re.match(r"^\d+\.\s+[\u4e00-\u9fff]", s) and len(s) < 50:
        return ("####", s)
    if re.match(r"^表\s*\d+\.\d+", s):
        return ("####", s)
    return None


